function dispatchLanguageChange() {
    document.dispatchEvent(new CustomEvent("portfolio:languagechange", {
        detail: {
            language: getStoredLanguage()
        }
    }));
}

function translateTagList(element, key) {
    const language = getStoredLanguage();
    const value = translations[language][key];

    if (!value) return;

    element.innerHTML = "";

    value.split("|").forEach((tag) => {
        const badge = document.createElement("span");
        badge.className = "px-1.5 py-0.5 rounded bg-white/5 text-[10px] font-mono text-zinc-300";
        badge.textContent = tag;
        element.appendChild(badge);
    });
}

function getStoredLanguage() {
    const stored = localStorage.getItem("portfolio-language");
    return stored === "en" ? "en" : "fr";
}

function setLanguage(language) {
    const selected = language === "en" ? "en" : "fr";

    localStorage.setItem("portfolio-language", selected);
    document.documentElement.lang = selected;

    document.querySelectorAll("[data-i18n]").forEach((element) => {
        const key = element.getAttribute("data-i18n");

        if (translations[selected][key]) {
            element.textContent = translations[selected][key];
        }
    });

    document.querySelectorAll("[data-i18n-placeholder]").forEach((element) => {
        const key = element.getAttribute("data-i18n-placeholder");

        if (translations[selected][key]) {
            element.placeholder = translations[selected][key];
        }
    });

    document.querySelectorAll("[data-i18n-tags]").forEach((element) => {
        const key = element.getAttribute("data-i18n-tags");
        translateTagList(element, key);
    });

    const pageTitle = document.getElementById("page-title");

    if (pageTitle && translations[selected]["meta.title"]) {
        pageTitle.textContent = translations[selected]["meta.title"];
    }

    const frButton = document.getElementById("lang-fr");
    const enButton = document.getElementById("lang-en");

    if (frButton && enButton) {
        frButton.classList.toggle("text-yaru-orange", selected === "fr");
        frButton.classList.toggle("font-bold", selected === "fr");
        frButton.setAttribute("aria-pressed", selected === "fr");

        enButton.classList.toggle("text-yaru-orange", selected === "en");
        enButton.classList.toggle("font-bold", selected === "en");
        enButton.setAttribute("aria-pressed", selected === "en");
    }

    const windowManagerTitles = {
        "stages-win": "window.stages",
        "projets-win": "window.projects",
        "terminal-win": "window.terminal",
        "cv-win": "window.cv",
        "contact-win": "window.contact",
        "skills-win": "window.skills",
        "parcours-win": "window.journey",
        "project-detail-win": "window.projectDetail"
    };

    const topBarName = document.getElementById("topbar-app-name");

    if (topBarName && wm && wm.activeWindowId && windowManagerTitles[wm.activeWindowId]) {
        topBarName.textContent = translations[selected][windowManagerTitles[wm.activeWindowId]];
    }
    dispatchLanguageChange();

    document.querySelectorAll("[data-i18n-title]").forEach((element) => {
        const key = element.getAttribute("data-i18n-title");

        if (translations[selected][key]) {
            element.setAttribute("title", translations[selected][key]);
        }
    });
}

document.addEventListener("DOMContentLoaded", () => {
    setLanguage(getStoredLanguage());

    const frButton = document.getElementById("lang-fr");
    const enButton = document.getElementById("lang-en");

    if (frButton) {
        frButton.addEventListener("click", () => setLanguage("fr"));
    }

    if (enButton) {
        enButton.addEventListener("click", () => setLanguage("en"));
    }
});